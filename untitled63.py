import os
import zipfile
import numpy as np
from collections import Counter, defaultdict

base_dir = "/content/drive/MyDrive/KITTI_Tracking"

image_zip = os.path.join(
    base_dir, "data_tracking_image_2.zip"
)
label_zip = os.path.join(
    base_dir, "data_tracking_label_2.zip"
)

assert os.path.isfile(image_zip), "Image ZIP missing"
assert os.path.isfile(label_zip), "Label ZIP missing"

image_pattern = "training/image_02/"
label_pattern = "training/label_02/"

# --------------------------------------------------
# 1. Read image frame inventory
# --------------------------------------------------

image_frames = defaultdict(set)

with zipfile.ZipFile(image_zip) as zf:
    for name in zf.namelist():
        if not name.startswith(image_pattern):
            continue

        parts = name.split("/")

        if len(parts) != 4:
            continue

        _, _, sequence, filename = parts

        if not filename.endswith(".png"):
            continue

        frame_id = int(os.path.splitext(filename)[0])
        image_frames[sequence].add(frame_id)

# --------------------------------------------------
# 2. Read label file inventory
# --------------------------------------------------

label_files = {}

with zipfile.ZipFile(label_zip) as zf:
    for name in zf.namelist():
        if not name.startswith(label_pattern):
            continue

        if not name.endswith(".txt"):
            continue

        sequence = os.path.splitext(
            os.path.basename(name)
        )[0]

        label_files[sequence] = name

    print("Label archive members:")
    for name in sorted(label_files.values()):
        print(name)

# --------------------------------------------------
# 3. Sequence correspondence
# --------------------------------------------------

image_sequences = set(image_frames.keys())
label_sequences = set(label_files.keys())

print("\n=== Sequence correspondence ===")
print("Image sequences:", len(image_sequences))
print("Label sequences:", len(label_sequences))

missing_labels = sorted(image_sequences - label_sequences)
extra_labels = sorted(label_sequences - image_sequences)

print("Missing labels:", missing_labels)
print("Extra labels:", extra_labels)

assert not missing_labels, "Some image sequences lack labels"
assert not extra_labels, "Unexpected label sequences"

# --------------------------------------------------
# 4. Parse and validate labels
# --------------------------------------------------

class_counts = Counter()
track_ids = defaultdict(set)
frame_label_counts = Counter()

total_rows = 0
invalid_rows = []
invalid_boxes = []
invalid_frames = []

with zipfile.ZipFile(label_zip) as zf:

    for sequence in sorted(label_sequences):

        content = zf.read(
            label_files[sequence]
        ).decode("utf-8")

        valid_image_ids = image_frames[sequence]

        for line_number, line in enumerate(
            content.splitlines(), start=1
        ):
            if not line.strip():
                continue

            fields = line.split()

            if len(fields) != 17:
                invalid_rows.append(
                    (sequence, line_number, len(fields))
                )
                continue

            try:
                frame_id = int(fields[0])
                track_id = int(fields[1])
                object_type = fields[2]

                numeric = np.asarray(
                    fields[3:],
                    dtype=np.float64
                )

            except (ValueError, TypeError):
                invalid_rows.append(
                    (sequence, line_number, "parse_error")
                )
                continue

            if not np.all(np.isfinite(numeric)):
                invalid_rows.append(
                    (sequence, line_number, "non_finite")
                )
                continue

            if frame_id not in valid_image_ids:
                invalid_frames.append(
                    (sequence, line_number, frame_id)
                )

            # fields[6:10] = bbox coordinates
            x1, y1, x2, y2 = map(
                float, fields[6:10]
            )

            if x2 <= x1 or y2 <= y1:
                invalid_boxes.append(
                    (sequence, line_number,
                     (x1, y1, x2, y2))
                )

            class_counts[object_type] += 1
            frame_label_counts[(sequence, frame_id)] += 1

            if track_id >= 0:
                track_ids[sequence].add(track_id)

            total_rows += 1

# --------------------------------------------------
# 5. Report
# --------------------------------------------------

print("\n=== Image inventory ===")

for sequence in sorted(image_frames):
    ids = image_frames[sequence]
    print(
        f"{sequence}: {len(ids)} frames | "
        f"range {min(ids)}–{max(ids)}"
    )

print("\n=== Label validation ===")
print("Total label rows:", total_rows)
print("Invalid row formats/parsing:", len(invalid_rows))
print("Invalid frame references:", len(invalid_frames))
print("Invalid bounding boxes:", len(invalid_boxes))

print("\n=== Class distribution ===")
for name, count in class_counts.most_common():
    print(f"{name}: {count:,}")

print("\n=== Track IDs per sequence ===")
for sequence in sorted(track_ids):
    print(
        f"{sequence}: "
        f"{len(track_ids[sequence])} unique IDs"
    )

print("\n=== Final checks ===")

checks = {
    "Sequence correspondence": (
        not missing_labels and not extra_labels
    ),
    "Label row format": len(invalid_rows) == 0,
    "Frame references": len(invalid_frames) == 0,
    "Bounding boxes": len(invalid_boxes) == 0,
}

for name, passed in checks.items():
    print(f"{name}: {'PASS' if passed else 'FAIL'}")

assert all(checks.values()), (
    "Label audit failed. Inspect the errors above."
)

print("\nIMAGE-LABEL STRUCTURAL AUDIT: PASS")

