import matplotlib.patches as patches
from PIL import Image
from io import BytesIO
from collections import defaultdict, Counter

base_dir = "/content/drive/MyDrive/KITTI_Tracking"

image_zip = os.path.join(base_dir, "data_tracking_image_2.zip")
label_zip = os.path.join(base_dir, "data_tracking_label_2.zip")

# Four candidates for visual inspection
sequences = ["0019", "0020", "0016", "0007"]

# Number of frames before/after the densest frame
temporal_offset = 30

# --------------------------------------------------
# 1. Load label rows for selected sequences
# --------------------------------------------------

labels = defaultdict(lambda: defaultdict(list))

with zipfile.ZipFile(label_zip) as zf:

    for sequence in sequences:

        member = f"training/label_02/{sequence}.txt"
        content = zf.read(member).decode("utf-8")

        for line in content.splitlines():

            if not line.strip():
                continue

            fields = line.split()

            frame_id = int(fields[0])
            track_id = int(fields[1])
            object_type = fields[2]

            bbox = tuple(map(float, fields[6:10]))

            labels[sequence][frame_id].append({
                "track_id": track_id,
                "class": object_type,
                "bbox": bbox
            })

# --------------------------------------------------
# 2. Select densest frame in each sequence
#    DontCare is excluded from the count.
# --------------------------------------------------

selected_frames = {}

for sequence in sequences:

    frame_counts = {
        frame_id: sum(
            obj["class"] != "DontCare"
            for obj in objects
        )
        for frame_id, objects in labels[sequence].items()
    }

    peak_frame = max(
        frame_counts,
        key=frame_counts.get
    )

    selected = sorted(set([
        max(0, peak_frame - temporal_offset),
        peak_frame,
        peak_frame + temporal_offset
    ]))

    selected_frames[sequence] = selected

    print(
        f"Sequence {sequence}: "
        f"peak frame={peak_frame}, "
        f"tracked objects={frame_counts[peak_frame]}, "
        f"samples={selected}"
    )

# --------------------------------------------------
# 3. Read image and visualize GT
# --------------------------------------------------

with zipfile.ZipFile(image_zip) as image_archive:

    for sequence in sequences:

        frames = selected_frames[sequence]

        fig, axes = plt.subplots(
            1, len(frames),
            figsize=(20, 6)
        )

        if len(frames) == 1:
            axes = [axes]

        for ax, frame_id in zip(axes, frames):

            image_path = (
                f"training/image_02/{sequence}/"
                f"{frame_id:06d}.png"
            )

            image_bytes = image_archive.read(image_path)
            image = Image.open(
                BytesIO(image_bytes)
            ).convert("RGB")

            ax.imshow(image)

            objects = labels[sequence].get(
                frame_id, []
            )

            for obj in objects:

                if obj["class"] == "DontCare":
                    continue

                x1, y1, x2, y2 = obj["bbox"]

                rect = patches.Rectangle(
                    (x1, y1),
                    x2 - x1,
                    y2 - y1,
                    linewidth=1.5,
                    edgecolor="lime",
                    facecolor="none"
                )

                ax.add_patch(rect)

                ax.text(
                    x1,
                    max(0, y1 - 4),
                    f'{obj["class"]} ID:{obj["track_id"]}',
                    color="yellow",
                    fontsize=7,
                    bbox=dict(
                        facecolor="black",
                        alpha=0.6,
                        pad=1
                    )
                )

            tracked_count = sum(
                obj["class"] != "DontCare"
                for obj in objects
            )

            ax.set_title(
                f"Seq {sequence} | Frame {frame_id}\n"
                f"Tracked objects: {tracked_count}"
            )

            ax.axis("off")

        plt.tight_layout()
        plt.show()

